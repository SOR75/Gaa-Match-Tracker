export const esc = (value) =>
  String(value ?? "").replace(
    /[&<>"']/g,
    (char) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        char
      ],
  );
export const field = (label, name, value = "", extra = "") =>
  `<label class="field"><span>${label}</span><input name="${name}" value="${esc(value)}" ${extra}></label>`;

